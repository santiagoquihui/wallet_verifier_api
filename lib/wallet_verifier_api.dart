/// Checks IDs in Apple Wallet with Apple's Verifier API (display requests),
/// and, on Android, reads ISO 18013-5 mobile driver's licenses directly (see
/// [verifyMdlFromQr] and [verifyMdlFromNfc]).
///
/// Requires iOS 17 or later and the
/// `com.apple.developer.proximity-reader.identity.display` entitlement.
/// Failed requests throw a [WalletVerifierException]; closing the reader
/// before a document is read throws [WalletVerifierErrorCode.cancelled].
class WalletVerifierApi {
  WalletVerifierApiPlatform get _platform => WalletVerifierApiPlatform.instance;

  /// Whether this device can read IDs with the Verifier API.
  ///
  /// Returns `false` below iOS 17.
  Future<bool> isSupported() => _platform.isSupported();

  /// Prepares the reader ahead of time so the next request opens faster.
  ///
  /// Optional: every request prepares the reader on demand. Pass a
  /// [readerToken] generated by your server to show your brand's name and
  /// logo in the system UI; see [readerInstanceIdentifier]. A token can be
  /// reused for up to 48 hours, after which requests fail with
  /// [WalletVerifierErrorCode.sessionExpired] and you need a new one.
  Future<void> prepare({String? readerToken}) =>
      _platform.prepare(readerToken: readerToken);

  /// The identifier your server exchanges for a reader token.
  ///
  /// Requires network access. Apple asks you not to cache this value.
  Future<String> readerInstanceIdentifier() =>
      _platform.readerInstanceIdentifier();

  /// Shows the requested [elements] of a mobile driver's license. iOS 17+.
  Future<ValidationOutcome> displayDriversLicense(
    List<DisplayElement> elements, {
    ValidationMode validationMode = ValidationMode.check,
  }) {
    return _platform.requestDisplay(
      DisplayRequest(
        document: DisplayDocument.driversLicense,
        elements: elements,
        validationMode: validationMode,
      ),
    );
  }

  /// Shows the requested [elements] of a national ID card issued by [region],
  /// an ISO 3166-1 region code such as `"JP"`. iOS 18+.
  ///
  /// Use [isNationalIDCardRegionSupported] to check the region first.
  Future<ValidationOutcome> displayNationalIDCard({
    required String region,
    required List<DisplayElement> elements,
    ValidationMode validationMode = ValidationMode.check,
  }) {
    return _platform.requestDisplay(
      DisplayRequest(
        document: DisplayDocument.nationalIDCard,
        elements: elements,
        validationMode: validationMode,
        region: region,
      ),
    );
  }

  /// Whether national ID cards issued by [region] can be read.
  ///
  /// Returns `false` below iOS 18.
  Future<bool> isNationalIDCardRegionSupported(String region) =>
      _platform.isNationalIDCardRegionSupported(region);

  /// Shows the requested [elements] of any of the [allowedDocumentTypes]
  /// (for example a driver’s license or a photo ID). iOS 26+.
  ///
  /// [allowedDocumentTypes] must be non-empty and free of duplicates; Apple
  /// treats any other list as an invalid request.
  Future<ValidationOutcome> displayDocument(
    List<DisplayElement> elements, {
    required List<DocumentType> allowedDocumentTypes,
    ValidationMode validationMode = ValidationMode.check,
  }) async {
    if (allowedDocumentTypes.isEmpty) {
      throw ArgumentError.value(
        allowedDocumentTypes,
        'allowedDocumentTypes',
        'must not be empty',
      );
    }
    if (allowedDocumentTypes.toSet().length != allowedDocumentTypes.length) {
      throw ArgumentError.value(
        allowedDocumentTypes,
        'allowedDocumentTypes',
        'must not contain duplicates',
      );
    }
    return _platform.requestDisplay(
      DisplayRequest(
        document: DisplayDocument.anyOf,
        elements: elements,
        validationMode: validationMode,
        allowedDocumentTypes: allowedDocumentTypes,
      ),
    );
  }

  /// Shows the requested [elements] of a mobile driver's license.
  @Deprecated('Use displayDriversLicense, which also returns the outcome.')
  Future<void> verifyAge(
    List<MobileDriversLicenseElement> elements, {
    int? age,
  }) async {
    if (elements.contains(MobileDriversLicenseElement.ageAtLeast) &&
        age == null) {
      throw ArgumentError(
        'age must be provided when ageAtLeast is included in elements',
      );
    }
    await displayDriversLicense([
      for (final element in elements)
        switch (element) {
          MobileDriversLicenseElement.givenName => DisplayElement.givenName,
          MobileDriversLicenseElement.familyName => DisplayElement.familyName,
          MobileDriversLicenseElement.age => DisplayElement.age,
          MobileDriversLicenseElement.ageAtLeast => DisplayElement.ageAtLeast(
            age!,
          ),
        },
    ]);
  }

  // ---------------------------------------------------------------------------
  // Android: ISO/IEC 18013-5 proximity reader (preview)
  // ---------------------------------------------------------------------------

  /// Whether this device can read mobile driver's licenses itself.
  ///
  /// `true` on Android 12+ with Bluetooth LE. Always `false` on iOS, where
  /// third-party apps must use [displayDriversLicense] instead.
  Future<bool> isAndroidReaderSupported() async {
    if (defaultTargetPlatform != TargetPlatform.android) return false;
    return _platform.isAndroidReaderSupported();
  }

  /// Whether the Bluetooth permissions the Android reader needs are granted.
  Future<bool> hasAndroidReaderPermissions() async {
    if (defaultTargetPlatform != TargetPlatform.android) return false;
    return _platform.hasAndroidReaderPermissions();
  }

  /// Asks for the Bluetooth permissions (scan, connect, advertise) the
  /// Android reader needs. Returns whether all were granted.
  Future<bool> requestAndroidReaderPermissions() async {
    if (defaultTargetPlatform != TargetPlatform.android) return false;
    return _platform.requestAndroidReaderPermissions();
  }

  /// Reads a mobile driver's license from the holder's engagement QR code
  /// (an `mdoc:` URI) over Bluetooth LE and verifies it. Android only.
  ///
  /// Every element is requested with intent-to-retain = false. The result's
  /// [MdlReadResult.isVerified] is `true` only when the data is intact and
  /// signed by a trusted issuer: the bundled Arizona IACA roots, any
  /// [additionalTrustedRootsPem], or the issuers in a signed AAMVA [vical].
  ///
  /// The signature check proves where the data came from, not who is holding
  /// the phone: still compare the portrait to the person.
  ///
  /// Throws a [WalletVerifierException]: [WalletVerifierErrorCode.notSupported]
  /// off Android, [WalletVerifierErrorCode.notAllowed] without Bluetooth
  /// permissions, [WalletVerifierErrorCode.invalidArgument] for a QR code that
  /// isn't an mdoc engagement, [WalletVerifierErrorCode.timedOut],
  /// [WalletVerifierErrorCode.transportFailed] or
  /// [WalletVerifierErrorCode.cancelled] (holder declined or [cancelMdlRead]).
  Future<MdlReadResult> verifyMdlFromQr(
    String qrContent, {
    List<MdlElement> elements = MdlElement.doorCheck,
    Duration timeout = const Duration(seconds: 45),
    List<String> additionalTrustedRootsPem = const [],
    Uint8List? vical,
  }) async {
    if (defaultTargetPlatform != TargetPlatform.android) {
      throw const WalletVerifierException(
        WalletVerifierErrorCode.notSupported,
        'The mDL reader is only available on Android',
      );
    }
    if (elements.isEmpty) {
      throw ArgumentError.value(elements, 'elements', 'must not be empty');
    }
    if (!MdocQrEngagement.isEngagement(qrContent)) {
      throw const WalletVerifierException(
        WalletVerifierErrorCode.invalidArgument,
        'Not an ISO 18013-5 engagement QR code',
      );
    }
    return _platform.readMdlFromQr(
      MdlQrReadRequest(
        qrContent: qrContent,
        elements: elements,
        timeout: timeout,
        additionalTrustedRootsPem: additionalTrustedRootsPem,
        vical: vical,
      ),
    );
  }

  /// This device's NFC state. [MdlNfcStatus.unsupported] off Android.
  Future<MdlNfcStatus> getNfcStatus() async {
    if (defaultTargetPlatform != TargetPlatform.android) {
      return MdlNfcStatus.unsupported;
    }
    return _platform.getNfcStatus();
  }

  /// Whether NFC is present and turned on, so [verifyMdlFromNfc] can run.
  Future<bool> isNfcAvailable() async =>
      await getNfcStatus() == MdlNfcStatus.enabled;

  /// Opens the system NFC settings so the person can turn NFC on. Returns
  /// whether a settings screen was opened. Android only.
  Future<bool> openNfcSettings() async {
    if (defaultTargetPlatform != TargetPlatform.android) return false;
    return _platform.openNfcSettings();
  }

  /// Waits for the holder to tap their phone against this one, then reads
  /// and verifies their mobile driver's license. Android only.
  ///
  /// While waiting, Android NFC reader mode is on for the current activity:
  /// keep your waiting screen in the foreground and tell the person to hold
  /// their phone against the back of this device. Works with ISO 18013-5 NFC
  /// static and negotiated handover (Apple Wallet, Google Wallet, Samsung
  /// Wallet); the data then moves over Bluetooth LE, or over NFC if that's all
  /// the wallet offers (the phones must then stay together).
  ///
  /// [timeout] covers the wait for a tap and the transfer. The result and the
  /// verification rules are the same as [verifyMdlFromQr], with
  /// [MdlReadResult.engagement] telling which handover was used.
  ///
  /// Throws a [WalletVerifierException]: [WalletVerifierErrorCode.notSupported]
  /// off Android or without NFC, [WalletVerifierErrorCode.nfcDisabled] when NFC
  /// is off (see [openNfcSettings]), [WalletVerifierErrorCode.notAllowed]
  /// without Bluetooth permissions, [WalletVerifierErrorCode.timedOut],
  /// [WalletVerifierErrorCode.transportFailed] or
  /// [WalletVerifierErrorCode.cancelled] (holder declined or [cancelMdlRead]).
  Future<MdlReadResult> verifyMdlFromNfc({
    List<MdlElement> elements = MdlElement.doorCheck,
    Duration timeout = const Duration(seconds: 60),
    List<String> additionalTrustedRootsPem = const [],
    Uint8List? vical,
  }) async {
    if (defaultTargetPlatform != TargetPlatform.android) {
      throw const WalletVerifierException(
        WalletVerifierErrorCode.notSupported,
        'The mDL reader is only available on Android',
      );
    }
    if (elements.isEmpty) {
      throw ArgumentError.value(elements, 'elements', 'must not be empty');
    }
    return _platform.readMdlFromNfc(
      MdlNfcReadRequest(
        elements: elements,
        timeout: timeout,
        additionalTrustedRootsPem: additionalTrustedRootsPem,
        vical: vical,
      ),
    );
  }

  /// Cancels the read started by [verifyMdlFromQr] or [verifyMdlFromNfc], if
  /// any, and turns NFC reader mode off.
  Future<void> cancelMdlRead() async {
    if (defaultTargetPlatform != TargetPlatform.android) return;
    return _platform.cancelMdlRead();
  }
}
